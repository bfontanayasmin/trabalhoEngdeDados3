# MAGIC %md
# MAGIC # Modelo dimensional na Gold
# MAGIC
# MAGIC O processo analisado é o registro de itens de pedidos da loja. A granularidade da fato é **uma linha por item de pedido**, identificado por `id_item`.
# MAGIC
# MAGIC ## Dimensões produto e cliente
# MAGIC
# MAGIC Cria `dim_produto` e `dim_cliente` com chaves substitutas (`sk_produto` e `sk_cliente`) geradas por identidade. A dimensão produto incorpora a categoria, evitando outra dimensão para esse atributo.
# MAGIC
# MAGIC O `MERGE` usa o identificador da origem para localizar o registro. Atualiza atributos existentes, sem manter versões históricas desses atributos (SCD tipo 1), e insere novos registros. Não remove dimensões que tenham deixado de existir na origem.
# MAGIC
# MAGIC O preço utilizado na fato será o preço do item no pedido, e não o preço atual do cadastro de produtos.

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE TABLE IF NOT EXISTS workspace.gold.dim_produto (
# MAGIC     sk_produto BIGINT GENERATED BY DEFAULT AS IDENTITY,
# MAGIC     id_produto INT,
# MAGIC     nome_produto STRING,
# MAGIC     id_categoria INT,
# MAGIC     nome_categoria STRING
# MAGIC )
# MAGIC USING DELTA;
# MAGIC
# MAGIC CREATE TABLE IF NOT EXISTS workspace.gold.dim_cliente (
# MAGIC     sk_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY,
# MAGIC     id_cliente INT,
# MAGIC     nome_cliente STRING,
# MAGIC     email STRING
# MAGIC )
# MAGIC USING DELTA;
# MAGIC
# MAGIC MERGE INTO workspace.gold.dim_produto AS destino
# MAGIC USING (
# MAGIC     SELECT
# MAGIC         p.id_produto,
# MAGIC         p.nome_produto,
# MAGIC         p.id_categoria,
# MAGIC         c.nome_categoria
# MAGIC     FROM workspace.silver.produtos p
# MAGIC     INNER JOIN workspace.silver.categorias c
# MAGIC         ON p.id_categoria = c.id_categoria
# MAGIC ) AS origem
# MAGIC ON destino.id_produto = origem.id_produto
# MAGIC
# MAGIC WHEN MATCHED THEN UPDATE SET
# MAGIC     destino.nome_produto = origem.nome_produto,
# MAGIC     destino.id_categoria = origem.id_categoria,
# MAGIC     destino.nome_categoria = origem.nome_categoria
# MAGIC
# MAGIC WHEN NOT MATCHED THEN INSERT (
# MAGIC     id_produto,
# MAGIC     nome_produto,
# MAGIC     id_categoria,
# MAGIC     nome_categoria
# MAGIC )
# MAGIC VALUES (
# MAGIC     origem.id_produto,
# MAGIC     origem.nome_produto,
# MAGIC     origem.id_categoria,
# MAGIC     origem.nome_categoria
# MAGIC );
# MAGIC
# MAGIC MERGE INTO workspace.gold.dim_cliente AS destino
# MAGIC USING workspace.silver.clientes AS origem
# MAGIC ON destino.id_cliente = origem.id_cliente
# MAGIC
# MAGIC WHEN MATCHED THEN UPDATE SET
# MAGIC     destino.nome_cliente = origem.nome_cliente,
# MAGIC     destino.email = origem.email
# MAGIC
# MAGIC WHEN NOT MATCHED THEN INSERT (
# MAGIC     id_cliente,
# MAGIC     nome_cliente,
# MAGIC     email
# MAGIC )
# MAGIC VALUES (
# MAGIC     origem.id_cliente,
# MAGIC     origem.nome_cliente,
# MAGIC     origem.email
# MAGIC );
# MAGIC
# MAGIC SELECT 'dim_produto' AS tabela, COUNT(*) AS registros
# MAGIC FROM workspace.gold.dim_produto
# MAGIC UNION ALL
# MAGIC SELECT 'dim_cliente', COUNT(*)
# MAGIC FROM workspace.gold.dim_cliente;

# COMMAND ----------

# MAGIC %md
# MAGIC ## Dimensão tempo
# MAGIC
# MAGIC Cria um calendário diário, do início do menor ano ao fim do maior ano presente nos pedidos da Silver. A chave `sk_tempo` usa o formato numérico `AAAAMMDD`.
# MAGIC
# MAGIC Inclui data, ano, trimestre, mês, dia e dia da semana. Para os pedidos iniciais de outubro de 2026, o calendário contém os 365 dias de 2026.

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE OR REPLACE TABLE workspace.gold.dim_tempo
# MAGIC USING DELTA
# MAGIC AS
# MAGIC WITH limites AS (
# MAGIC     SELECT
# MAGIC         trunc(MIN(data_pedido), 'YEAR') AS inicio,
# MAGIC         last_day(
# MAGIC             add_months(trunc(MAX(data_pedido), 'YEAR'), 11)
# MAGIC         ) AS fim
# MAGIC     FROM workspace.silver.pedidos
# MAGIC ),
# MAGIC calendario AS (
# MAGIC     SELECT explode(
# MAGIC         sequence(inicio, fim, INTERVAL 1 DAY)
# MAGIC     ) AS data
# MAGIC     FROM limites
# MAGIC     WHERE inicio IS NOT NULL
# MAGIC )
# MAGIC SELECT
# MAGIC     CAST(date_format(data, 'yyyyMMdd') AS INT) AS sk_tempo,
# MAGIC     data,
# MAGIC     year(data) AS ano,
# MAGIC     quarter(data) AS trimestre,
# MAGIC     month(data) AS mes,
# MAGIC     dayofmonth(data) AS dia,
# MAGIC     dayofweek(data) AS dia_semana
# MAGIC FROM calendario;

# COMMAND ----------

# MAGIC %md
# MAGIC ## Fato de itens de pedido
# MAGIC
# MAGIC Relaciona itens e pedidos da Silver com as três dimensões Gold. Mantém identificadores do item e do pedido e o status do pedido.
# MAGIC
# MAGIC As medidas são quantidade, preço unitário e valor total do item (`quantidade × preco_unitario`). O preço unitário não deve ser somado como se fosse um total financeiro.
# MAGIC
# MAGIC Inclui todos os status, inclusive pedidos em preparação. Portanto, o total desta tabela representa o valor dos itens de todos os pedidos, não somente vendas concluídas.
# MAGIC
# MAGIC A tabela fato é reconstruída em cada carga, evitando acumular os mesmos itens em execuções repetidas.

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE OR REPLACE TABLE workspace.gold.fato_itens_pedido
# MAGIC USING DELTA
# MAGIC AS
# MAGIC SELECT
# MAGIC     i.id_item,
# MAGIC     i.id_pedido,
# MAGIC     dp.sk_produto,
# MAGIC     dc.sk_cliente,
# MAGIC     dt.sk_tempo,
# MAGIC     p.status_pedido,
# MAGIC     i.quantidade,
# MAGIC     i.preco_unitario,
# MAGIC     CAST(
# MAGIC         i.quantidade * i.preco_unitario AS DECIMAL(18,2)
# MAGIC     ) AS valor_total
# MAGIC FROM workspace.silver.itens_pedido i
# MAGIC INNER JOIN workspace.silver.pedidos p
# MAGIC     ON i.id_pedido = p.id_pedido
# MAGIC INNER JOIN workspace.gold.dim_produto dp
# MAGIC     ON i.id_produto = dp.id_produto
# MAGIC INNER JOIN workspace.gold.dim_cliente dc
# MAGIC     ON p.id_cliente = dc.id_cliente
# MAGIC INNER JOIN workspace.gold.dim_tempo dt
# MAGIC     ON p.data_pedido = dt.data;

# COMMAND ----------

# MAGIC %md
# MAGIC ## Reconciliação da Gold
# MAGIC
# MAGIC Confere se a quantidade de itens é igual à Silver, se `id_item` é único e se o total financeiro calculado na Silver coincide com o total da Gold.
# MAGIC
# MAGIC Resultados iniciais: 10 produtos, 5 clientes, 365 datas, 10 itens de pedido e R$ 690,40 somando todos os status.

# COMMAND ----------

from decimal import Decimal

fato = spark.table("workspace.gold.fato_itens_pedido")
itens = spark.table("workspace.silver.itens_pedido")

assert fato.count() == itens.count(), "Quantidade de itens diferente."

assert fato.select("id_item").distinct().count() == fato.count(), (
    "Há itens duplicados na fato."
)

total_silver = spark.sql("""
    SELECT SUM(quantidade * preco_unitario) AS total
    FROM workspace.silver.itens_pedido
""").first()["total"]

total_gold = spark.sql("""
    SELECT SUM(valor_total) AS total
    FROM workspace.gold.fato_itens_pedido
""").first()["total"]

assert total_gold == total_silver, "Total financeiro diferente."

for tabela in [
    "dim_produto",
    "dim_cliente",
    "dim_tempo",
    "fato_itens_pedido"
]:
    quantidade = spark.table(f"workspace.gold.{tabela}").count()
    print(f"{tabela}: {quantidade} registros")

print(f"Valor total dos itens de todos os pedidos: R$ {total_gold:.2f}")
print("Gold concluída e validada.")
